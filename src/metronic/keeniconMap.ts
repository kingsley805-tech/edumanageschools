const KEENICON_FALLBACK = "element-11";

export function keeniconFor(icon: LucideIcon | undefined): string {
  if (!icon) return KEENICON_FALLBACK;
  const name = icon.displayName ?? icon.name;
  if (!name) return KEENICON_FALLBACK;
  return KEENICON_BY_LUCIDE[name] ?? KEENICON_FALLBACK;
}

